def build_annotations():
    """RAW_DATA → annotations.json 생성."""
    out_dir = Path("data/labels")
    out_dir.mkdir(parents=True, exist_ok=True)

    samples = []
    errors = []

    for raw in RAW_DATA:
        sid = raw["id"]
        items = raw["items"]

        # 검증: items 합계 = raw_score
        computed = sum(items.values())
        expected = raw["raw_score"]
        if computed != expected:
            errors.append(
                f"{sid}: items 합계={computed} ≠ raw_score={expected} (차이 {computed - expected:+d})"
            )

        # figure_gender에 맞는 scale 결정
        # 여아가 여자상을 그릴 때 female scale, 나머지는 male scale
        if raw["child_gender"] == "female" and raw["figure_gender"] == "female":
            scale = "female"
        else:
            scale = "male"

        head_labels = items_to_head_labels(items, scale=scale)

        samples.append({
            "id": sid,
            "image_path": raw["image_path"],
            "child_gender": raw["child_gender"],
            "figure_gender": raw["figure_gender"],
            "child_age": raw["child_age"],
            "raw_score": raw["raw_score"],
            "items": items,
            "head_labels": head_labels,
        })

    if errors:
        print("⚠️  원점수 불일치 발견:")
        for e in errors:
            print(f"   {e}")
    else:
        print("✅ 모든 샘플 원점수 검증 통과")

    out_path = out_dir / "annotations.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump({"samples": samples}, f, ensure_ascii=False, indent=2)

    print(f"✅ 저장: {out_path} ({len(samples)}개 샘플)")

    # 통계 출력
    print(f"\n📊 데이터셋 통계:")
    print(f"  총 샘플: {len(samples)}")
    male_fig = sum(1 for s in samples if s["figure_gender"] == "male")
    female_fig = sum(1 for s in samples if s["figure_gender"] == "female")
    print(f"  남자상: {male_fig}개, 여자상: {female_fig}개")
    ages = [s["child_age"] for s in samples]
    print(f"  연령 범위: {min(ages)}~{max(ages)}세")
    scores = [s["raw_score"] for s in samples]
    print(f"  원점수 범위: {min(scores)}~{max(scores)}점 (평균 {sum(scores)/len(scores):.1f}점)")


if __name__ == "__main__":
    build_annotations()
